using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Threading.Tasks;

namespace ModernFormsNext.WindowKit.Input
{
    /// <summary>
    /// Identifies a mouse button in pointer input.
    /// </summary>
    public enum MouseButton
    {
        /// <summary>
        /// No mouse button.
        /// </summary>
        None,

        /// <summary>
        /// The left mouse button.
        /// </summary>
        Left,

        /// <summary>
        /// The right mouse button.
        /// </summary>
        Right,

        /// <summary>
        /// The middle mouse button.
        /// </summary>
        Middle,

        /// <summary>
        /// The first extended mouse button.
        /// </summary>
        XButton1,

        /// <summary>
        /// The second extended mouse button.
        /// </summary>
        XButton2
    }
}
