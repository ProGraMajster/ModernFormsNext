namespace ModernFormsNext.WindowKit.Backend.Android.Rendering;

/// <summary>Identifies editing and navigation keys forwarded by the Android surface.</summary>
public enum AndroidInputKey
{
    /// <summary>The backward-delete key.</summary>
    Backspace,
    /// <summary>The forward-delete key.</summary>
    Delete,
    /// <summary>The enter or return key.</summary>
    Enter,
    /// <summary>The left-arrow key.</summary>
    Left,
    /// <summary>The up-arrow key.</summary>
    Up,
    /// <summary>The right-arrow key.</summary>
    Right,
    /// <summary>The down-arrow key.</summary>
    Down
}
