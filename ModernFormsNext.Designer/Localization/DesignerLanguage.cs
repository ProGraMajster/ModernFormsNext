namespace ModernFormsNext.Designer.Localization;

/// <summary>
/// Identifies the language used by ModernFormsNext designer UI strings.
/// </summary>
public enum DesignerLanguage
{
    /// <summary>
    /// Uses <see cref="System.Globalization.CultureInfo.CurrentUICulture"/> to select the language.
    /// </summary>
    Auto,

    /// <summary>
    /// Uses English designer UI strings.
    /// </summary>
    English,

    /// <summary>
    /// Uses Polish designer UI strings.
    /// </summary>
    Polish
}
