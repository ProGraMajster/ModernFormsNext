namespace ModernFormsNext.Designer.Layout;

/// <summary>
/// Describes the outer dock side used by a designer tool window.
/// </summary>
public enum DesignerToolWindowSide
{
    /// <summary>
    /// The tool window is docked along the left side of the designer workspace.
    /// </summary>
    Left,

    /// <summary>
    /// The tool window is docked along the right side of the designer workspace.
    /// </summary>
    Right,

    /// <summary>
    /// The tool window is docked along the bottom side of the designer workspace.
    /// </summary>
    Bottom
}
