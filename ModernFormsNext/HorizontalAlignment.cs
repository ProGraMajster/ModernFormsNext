namespace ModernFormsNext
{
    /// <summary>
    /// Specifies horizontal text alignment for controls that expose a WinForms-compatible alignment API.
    /// </summary>
    public enum HorizontalAlignment
    {
        /// <summary>
        /// Aligns text to the left edge of the control.
        /// </summary>
        Left = 0,

        /// <summary>
        /// Aligns text to the right edge of the control.
        /// </summary>
        Right = 1,

        /// <summary>
        /// Centers text horizontally in the control.
        /// </summary>
        Center = 2
    }
}
