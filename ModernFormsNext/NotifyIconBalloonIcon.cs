namespace ModernFormsNext
{
    /// <summary>
    /// Specifies the icon shown in a <see cref="NotifyIcon"/> balloon notification.
    /// </summary>
    public enum NotifyIconBalloonIcon
    {
        /// <summary>
        /// No icon is requested.
        /// </summary>
        None,

        /// <summary>
        /// An informational icon is requested.
        /// </summary>
        Info,

        /// <summary>
        /// A warning icon is requested.
        /// </summary>
        Warning,

        /// <summary>
        /// An error icon is requested.
        /// </summary>
        Error
    }
}
